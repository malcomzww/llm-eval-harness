"""Generate the results this repo commits.

Follows the split established in llm-client-kit: machine-independent claims go
into a committed file, anything machine-dependent goes to a gitignored raw
file. Here almost everything is machine-independent already, because the
subject is statistical behaviour rather than wall-clock timing.

The demonstration below uses synthetic score distributions with known
properties, not a live model. That is deliberate and stated in the output: the
claim under test is that the *harness* refuses to report a difference it
cannot support, and a real model's noise would obscure rather than
demonstrate it.

Run:  python scripts/generate_results.py
"""

from __future__ import annotations

import random
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from llm_eval_harness.stats import (  # noqa: E402
    bootstrap_ci,
    cohen_kappa,
    is_reportable,
    mean,
    min_n_for_delta,
    paired_delta_ci,
)

RESULTS = Path(__file__).resolve().parent.parent / "results"
OUT = RESULTS / "reporting-rule.md"

SEED = 0
N = 200


def _scores(rng: random.Random, p: float, n: int = N) -> list[float]:
    """n Bernoulli scores with success probability p."""
    return [1.0 if rng.random() < p else 0.0 for _ in range(n)]


def main() -> None:
    rng = random.Random(SEED)

    # Two systems that are genuinely identical. Any observed difference here
    # is noise, and the harness must refuse to call it an improvement.
    a_null = _scores(rng, 0.70)
    b_null = _scores(rng, 0.70)
    d_null, lo_null, hi_null = paired_delta_ci(a_null, b_null, seed=SEED)

    # Two systems that genuinely differ by 10 points.
    a_real = _scores(rng, 0.60)
    b_real = _scores(rng, 0.70)
    d_real, lo_real, hi_real = paired_delta_ci(a_real, b_real, seed=SEED)

    # A judge agreeing with a human on 85% of items, and one agreeing at
    # chance. Kappa should separate them even though raw agreement does not
    # look dramatically different.
    human = _scores(rng, 0.5)
    good_judge = [h if rng.random() < 0.85 else 1.0 - h for h in human]
    coin_judge = _scores(rng, 0.5)
    k_good = cohen_kappa(human, good_judge)
    k_coin = cohen_kappa(human, coin_judge)

    # Assertions. If any of these break the claim in the README is wrong, and
    # this script must fail rather than emit a file that says otherwise.
    assert not is_reportable(d_null, (lo_null, hi_null)), (
        f"two identical systems produced a reportable delta: {d_null:+.4f} "
        f"[{lo_null:+.4f}, {hi_null:+.4f}] -- the reporting rule is broken"
    )
    assert is_reportable(d_real, (lo_real, hi_real)), (
        f"a real 10-point difference was not detected at n={N}: {d_real:+.4f} "
        f"[{lo_real:+.4f}, {hi_real:+.4f}]"
    )
    assert k_good > 0.5, f"an 85%-agreeing judge scored kappa={k_good:.3f}"
    assert abs(k_coin) < 0.3, f"a coin-flip judge scored kappa={k_coin:.3f}"

    L: list[str] = []
    add = L.append
    add("# The reporting rule, demonstrated\n")
    add("Generated by `python scripts/generate_results.py`. Do not edit by hand.\n")
    add(f"- Date: {date.today().isoformat()}")
    add("- Hardware: irrelevant. These are statistical properties, not timings")
    add(f"- Seed: {SEED} (fixed; the file regenerates identically)")
    add(f"- Sample size: {N} per system")
    add("- Reproduce: `python scripts/generate_results.py`")
    add("- Data: synthetic Bernoulli scores with known success rates\n")
    add("Synthetic on purpose. The claim under test is that this harness")
    add("refuses to report a difference it cannot support, and real model")
    add("noise would obscure that rather than demonstrate it.\n")

    add("## Two identical systems\n")
    add("Both draw from the same 70% distribution, so the true difference is")
    add("exactly zero.\n")
    add(f"- observed delta: **{d_null:+.4f}**")
    add(f"- 95% CI: [{lo_null:+.4f}, {hi_null:+.4f}]")
    add("- **reportable: no** — the interval includes zero\n")
    add("The point estimate is not zero, and never will be. Quoting it as an")
    add("improvement is the most common way eval results mislead, so the")
    add("harness labels it unreportable instead.\n")

    add("## Two systems that genuinely differ\n")
    add("60% versus 70%, same sample size.\n")
    add(f"- observed delta: **{d_real:+.4f}**")
    add(f"- 95% CI: [{lo_real:+.4f}, {hi_real:+.4f}]")
    add("- **reportable: yes** — the interval excludes zero\n")

    add("## Kappa separates a good judge from a coin flip\n")
    add("| judge | agreement with human | Cohen's kappa |")
    add("|---|---|---|")
    agree_good = sum(1 for x, y in zip(human, good_judge, strict=True) if x == y) / N
    agree_coin = sum(1 for x, y in zip(human, coin_judge, strict=True) if x == y) / N
    add(f"| 85%-agreeing | {agree_good:.0%} | **{k_good:.3f}** |")
    add(f"| coin flip | {agree_coin:.0%} | **{k_coin:.3f}** |")
    add("")
    add("Raw agreement makes the coin flip look respectable. Kappa subtracts")
    add("the agreement expected by chance and puts it near zero, which is why")
    add("this harness calibrates on kappa rather than accuracy.\n")

    add("## How large a golden set needs to be\n")
    add("Samples per arm to detect a given difference at 80% power, two-sided")
    add("alpha 0.05, sd 0.5:\n")
    add("| difference to detect | samples per arm |")
    add("|---|---|")
    for d in (0.01, 0.02, 0.05, 0.10, 0.20):
        add(f"| {d:.0%} | {min_n_for_delta(d, 0.5):,} |")
    add("")
    add("Worth computing before building the set rather than after: a")
    add("100-item golden set cannot resolve a 2-point difference, and no")
    add("amount of careful judging changes that.\n")

    add("## Limitations\n")
    add("- Synthetic Bernoulli data. Real eval scores are often bounded,")
    add("  skewed or bimodal; the bootstrap handles those, but this file does")
    add("  not demonstrate it on real distributions.")
    add("- Sample sizing uses a normal approximation, which is loose for very")
    add("  small n or extreme proportions.")
    add("- Kappa here is binary. Multi-category and weighted kappa behave")
    add("  differently and are not established by this file.\n")

    RESULTS.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parent.parent)}")
    print(f"  null delta   {d_null:+.4f} [{lo_null:+.4f}, {hi_null:+.4f}] not reportable")
    print(f"  real delta   {d_real:+.4f} [{lo_real:+.4f}, {hi_real:+.4f}] reportable")
    print(f"  kappa good={k_good:.3f} coin={k_coin:.3f}")
    print(f"  mean(a_null)={mean(a_null):.3f} ci={bootstrap_ci(a_null, seed=SEED)}")


if __name__ == "__main__":
    main()
